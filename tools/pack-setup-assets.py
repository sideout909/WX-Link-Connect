#!/usr/bin/env python3
"""Pack checked-in browser assets into deterministic gzip firmware arrays."""
import gzip
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FILES = [
    ('leaflet_js', 'assets/web/leaflet/leaflet.js', 'db49d009c841f5ca34a888c96511ae936fd9f5533e90d8b2c4d57596f4e5641a'),
    ('leaflet_css', 'assets/web/leaflet/leaflet.css', 'a7837102824184820dfa198d1ebcd109ff6d0ff9a2672a074b9a1b4d147d04c6'),
    ('location_js', 'assets/web/location.js', None),
    ('dashboard_js', 'assets/web/dashboard.js', None),
    ('discovery_js', 'assets/web/discovery.js', None),
]
with (ROOT/'firmware/include/setup_assets.h').open('w') as out:
    out.write('// Generated by tools/pack-setup-assets.py. Leaflet license: assets/web/leaflet/LICENSE\n'
              '#pragma once\n#include <Arduino.h>\nnamespace setup_assets {\n')
    for name, path, expected in FILES:
        raw = (ROOT/path).read_bytes()
        if expected and hashlib.sha256(raw).hexdigest() != expected:
            raise ValueError(f'Pinned asset checksum differs: {path}')
        packed = gzip.compress(raw, compresslevel=9, mtime=0)
        out.write(f'static const uint8_t {name}[] PROGMEM = {{\n')
        for start in range(0, len(packed), 24):
            out.write('  '+','.join(str(v) for v in packed[start:start+24])+',\n')
        out.write('};\n')
        print(f'{path}: {len(raw)} bytes → {len(packed)} gzip bytes')
    out.write('}\n')
