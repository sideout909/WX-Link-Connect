#!/usr/bin/env python3
"""Generate matching firmware palettes, embedded CSS and original icon variants."""
import json
from pathlib import Path
import re
import subprocess
import tempfile

ROOT=Path(__file__).resolve().parents[1]
THEMES=json.loads((ROOT/'assets/themes/palettes.json').read_text())
ROLES=['background','card','text','muted','accent','divider','connected','alert_card','alert_border','stale']

def rgb565(value):
 r,g,b=bytes.fromhex(value[1:]);return ((r&248)<<8)|((g&252)<<3)|(b>>3)

lines=['// Generated by tools/pack-display-themes.py from assets/themes/palettes.json.', '#pragma once','#include <cstdint>','#include <cstring>','namespace display_themes {','struct Palette {const char* id;'+''.join('uint16_t '+key+';' for key in ROLES)+'uint8_t brightness;};','inline constexpr Palette palettes[]={']
for key,t in THEMES.items():lines.append('  {"'+key+'",'+','.join(hex(rgb565(t[role])) for role in ROLES)+','+str(t.get('brightness',160))+'},')
lines += ['};','inline const Palette* find(const char* id){if(!id)return nullptr;for(const auto& p:palettes)if(!std::strcmp(p.id,id))return &p;return nullptr;}','inline const Palette& get(const char* id){const auto* p=find(id);return p?*p:palettes[0];}','}']
(ROOT/'firmware/include/display_themes.h').write_text('\n'.join(lines)+'\n')

css=[]
for key,t in THEMES.items():
 values={'bg':t['background'],'card':t['card'],'line':t['divider'],'muted':t['muted'],'cyan':t['accent'],'white':t['text'],'green':t['connected'],'alert-card':t['alert_card'],'alert-border':t['alert_border'],'amber':t['stale'],'input':t['background'],'button-ink':t['button_ink']}
 css.append(':root[data-theme="'+key+'"]{color-scheme:'+t['scheme']+';'+''.join('--'+name+':'+value+';' for name,value in values.items())+'}')
p=ROOT/'firmware/include/setup_page.h';page=p.read_text()
block='/* BEGIN DISPLAY THEMES */\n'+'\n'.join(css)+'\n/* END DISPLAY THEMES */'
if '/* BEGIN DISPLAY THEMES */' in page:page=re.sub(r'/\* BEGIN DISPLAY THEMES \*/.*?/\* END DISPLAY THEMES \*/',lambda _:block,page,flags=re.S)
else:page=page.replace('*{box-sizing:border-box}',block+'\n*{box-sizing:border-box}',1)
p.write_text(page)

names=['sunny','partly-cloudy','cloudy','rain','thunderstorm','snow','fog','windy','unknown']
lines=['// Generated from original SVGs by tools/pack-display-themes.py.', '#pragma once','#include <Arduino.h>','#include <cstring>','#include "weather_icons.h"','namespace theme_icons {','struct Icon {const char* theme;const char* name;const uint8_t* bytes;size_t size;};']
entries=[]
with tempfile.TemporaryDirectory(prefix='cyd-theme-icons-') as tmp:
 for key,t in THEMES.items():
  for name in names:
   symbol=key.replace('-','_')+'_'+name.replace('-','_')
   if key=='midnight':
    var='weather_icons::'+name.replace('-','_');entries.append('{"midnight","'+name+'",'+var+',sizeof('+var+')}');continue
   svg=(ROOT/'assets/weather'/f'{name}.svg').read_text()
   mapping={'#244359':t['card'],'#72def0':t['accent'],'#f0f5fb':t['text'],'#c7d8e9':t['muted'],'#d9eaff':t['text']}
   if key in ('matrix','night'):mapping['#ffcd70']=t['accent']
   svg=re.sub(r'#[0-9a-fA-F]{6}',lambda m:mapping.get(m[0],m[0]),svg)
   source=Path(tmp)/'icon.svg';png=Path(tmp)/'icon.png';source.write_text(svg)
   subprocess.run(['rsvg-convert',str(source),'-o',str(png)],check=True)
   data=png.read_bytes();lines.append('inline const uint8_t '+symbol+'[] PROGMEM={')
   for start in range(0,len(data),24):lines.append('  '+','.join(str(v) for v in data[start:start+24])+',')
   lines.append('};');entries.append('{"'+key+'","'+name+'",'+symbol+',sizeof('+symbol+')}')
lines+=['inline const Icon icons[]={'+',\n'.join(entries)+'};','inline const Icon* find(const char* theme,const char* name){for(const auto& i:icons)if(!std::strcmp(i.theme,theme)&&!std::strcmp(i.name,name))return &i;return nullptr;}','}']
(ROOT/'firmware/include/theme_icons.h').write_text('\n'.join(lines)+'\n')
print(f'Generated {len(THEMES)} shared palettes and {len(THEMES)-1} sets of nine original icon variants.')
