#!/usr/bin/env python3
"""Pack DejaVu glyph coverage for the code-drawn Home v2 interface.

Requires Pillow and DejaVu Sans Book/Bold (the concept SVG's font family).
Only the generator needs the desktop fonts; the device uses the packed header.
"""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--font-dir', type=Path, default=Path('/usr/share/fonts/TTF'))
args = parser.parse_args()
characters = ''.join(chr(c) for c in range(32, 127)) + '°·‹›—'
variants = [('small', 7, False), ('status', 8, False), ('unit', 9, False),
            ('body', 10, False), ('label', 10, True), ('tile_label', 9, True),
            ('header', 11, True), ('callsign', 14, True), ('clock', 11, False), ('alert', 13, True),
            ('event', 12, False), ('event_bold', 12, True), ('reading', 20, False),
            ('wind', 28, True), ('temperature_compact', 39, True), ('temperature', 49, True)]
with (ROOT / 'firmware/include/home_fonts.h').open('w') as out:
    out.write('// Generated by tools/pack-home-fonts.py. DejaVu license: assets/fonts/LICENSE-DejaVu.txt\n'
              '#pragma once\n#include <stdint.h>\nnamespace home_fonts {\n'
              'struct Glyph { uint16_t code; uint32_t offset; uint8_t width, height; int8_t left, top; uint16_t advance; };\n'
              'struct Font { const uint8_t* pixels; const Glyph* glyphs; uint16_t count; };\n')
    for name, size, bold in variants:
        font = ImageFont.truetype(str(args.font_dir / ('DejaVuSans-Bold.ttf' if bold else 'DejaVuSans.ttf')), size)
        # Large numbers need only numeric glyphs, minus and decimal point.
        charset = characters if size < 20 else ' -.0123456789'
        pixels, glyphs = [], []
        for char in charset:
            left, top, right, bottom = font.getbbox(char, anchor='ls')
            width, height = right-left, bottom-top
            bitmap = Image.new('L', (width, height))
            ImageDraw.Draw(bitmap).text((-left, -top), char, font=font, fill=255, anchor='ls')
            coverage = [(p+8)//17 for p in bitmap.tobytes()]
            offset = len(pixels)
            pixels.extend((coverage[i] << 4) | (coverage[i+1] if i+1 < len(coverage) else 0)
                          for i in range(0, len(coverage), 2))
            glyphs.append((ord(char), offset, width, height, left, top, round(font.getlength(char)*64)))
        out.write(f'inline constexpr uint8_t {name}_pixels[] = {{\n')
        for start in range(0, len(pixels), 32):
            out.write('  '+','.join(str(v) for v in pixels[start:start+32])+',\n')
        out.write('};\n'+f'inline constexpr Glyph {name}_glyphs[] = {{\n')
        for glyph in glyphs:
            out.write('  {'+','.join(str(v) for v in glyph)+'},\n')
        out.write('};\n'+f'inline constexpr Font {name} = {{{name}_pixels,{name}_glyphs,{len(glyphs)}}};\n')
    out.write('}\n')
